//go:build ignore

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// This script generates embedded_protos_generated.go containing:
//   - Proto file contents as string constants
//   - A registry map and module list for runtime lookup
//   - Helper functions (ScanModulesInEmbeddedProtoDir, ReadEmbeddedProtoFile, etc.)
//
// It automatically discovers query.proto and tx.proto files under ../../proto/guru/.
func main() {
	type protoFile struct {
		varName   string
		filePath  string
		protoPath string // canonical path: proto/guru/{module}/v1/{file}
		module    string
	}

	// targetFiles defines which proto filenames to embed (swagger-relevant service definitions).
	targetFiles := map[string]string{
		"query.proto": "Query",
		"tx.proto":    "Tx",
	}

	protoBaseDir := filepath.Join("..", "..", "proto", "guru")

	var protoFiles []protoFile
	moduleSet := make(map[string]bool)

	// Walk proto/guru/ to automatically discover target proto files.
	err := filepath.Walk(protoBaseDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}

		suffix, ok := targetFiles[info.Name()]
		if !ok {
			return nil
		}

		// Extract module name from path: ../../proto/guru/{module}/v1/{file}.proto
		rel, err := filepath.Rel(protoBaseDir, path)
		if err != nil {
			return fmt.Errorf("failed to compute relative path for %s: %w", path, err)
		}
		parts := strings.Split(filepath.ToSlash(rel), "/")
		if len(parts) < 2 {
			return nil
		}
		module := parts[0] // e.g. "oracle", "bex"

		varName := module + suffix + "Proto"
		protoPath := "proto/guru/" + filepath.ToSlash(rel) // canonical path for runtime lookup

		moduleSet[module] = true
		protoFiles = append(protoFiles, protoFile{
			varName:   varName,
			filePath:  path,
			protoPath: protoPath,
			module:    module,
		})
		return nil
	})
	if err != nil {
		fmt.Printf("Error walking proto directory %s: %v\n", protoBaseDir, err)
		os.Exit(1)
	}

	if len(protoFiles) == 0 {
		fmt.Printf("No target proto files found under %s\n", protoBaseDir)
		os.Exit(1)
	}

	sort.Slice(protoFiles, func(i, j int) bool {
		return protoFiles[i].varName < protoFiles[j].varName
	})

	// Sort modules alphabetically for deterministic output.
	var modules []string
	for m := range moduleSet {
		modules = append(modules, m)
	}
	sort.Strings(modules)

	// --- Build the generated file ---
	var output strings.Builder
	output.WriteString("// Code generated by generate_embedded_protos.go; DO NOT EDIT.\n\n")
	output.WriteString("package swagger\n\n")
	output.WriteString("import \"fmt\"\n\n")

	// 1. Proto content constants
	for _, pf := range protoFiles {
		content, err := os.ReadFile(pf.filePath)
		if err != nil {
			fmt.Printf("Error reading %s: %v\n", pf.filePath, err)
			os.Exit(1)
		}
		escaped := strings.ReplaceAll(string(content), "`", "` + \"`\" + `")
		output.WriteString(fmt.Sprintf("// %s contains the content of %s\n", pf.varName, pf.protoPath))
		output.WriteString(fmt.Sprintf("const %s = `%s`\n\n", pf.varName, escaped))
	}

	// 2. Registry map (proto path → constant variable)
	output.WriteString("// embeddedProtoRegistry maps canonical proto paths to their content.\n")
	output.WriteString("var embeddedProtoRegistry = map[string]string{\n")
	for _, pf := range protoFiles {
		output.WriteString(fmt.Sprintf("\t%q: %s,\n", pf.protoPath, pf.varName))
	}
	output.WriteString("}\n\n")

	// 3. Module list
	output.WriteString("// embeddedModules lists all discovered module names (sorted).\n")
	output.WriteString("var embeddedModules = []string{\n")
	for _, m := range modules {
		output.WriteString(fmt.Sprintf("\t%q,\n", m))
	}
	output.WriteString("}\n\n")

	// 4. Helper functions
	output.WriteString(`// ScanModulesInEmbeddedProtoDir returns all module names found in the embedded proto directory.
func ScanModulesInEmbeddedProtoDir(_ string) ([]string, error) {
	result := make([]string, len(embeddedModules))
	copy(result, embeddedModules)
	return result, nil
}

// ReadEmbeddedProtoFile reads a proto file content from the embedded registry.
func ReadEmbeddedProtoFile(protoPath string) (string, error) {
	content, ok := embeddedProtoRegistry[protoPath]
	if !ok {
		return "", fmt.Errorf("embedded proto file %s not found", protoPath)
	}
	return content, nil
}

// CheckEmbeddedProtoFileExists checks if a proto file exists in the embedded registry.
func CheckEmbeddedProtoFileExists(protoPath string) bool {
	_, ok := embeddedProtoRegistry[protoPath]
	return ok
}

// ListEmbeddedProtoFiles returns all proto file paths in the embedded registry.
func ListEmbeddedProtoFiles() ([]string, error) {
	files := make([]string, 0, len(embeddedProtoRegistry))
	for path := range embeddedProtoRegistry {
		files = append(files, path)
	}
	return files, nil
}
`)

	// Write the generated file
	err = os.WriteFile("embedded_protos_generated.go", []byte(output.String()), 0644)
	if err != nil {
		fmt.Printf("Error writing generated file: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated embedded_protos_generated.go successfully (%d modules, %d proto files)\n",
		len(modules), len(protoFiles))
}
